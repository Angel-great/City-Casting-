export default function Sidebar() {
  const pathname = usePathname();
  const { user, logout } = useAuthStore();

  const isEmployee =
    user?.role === "ACCOUNT_MANAGER" ||
    user?.role === "DEPARTMENT_EMPLOYEE" ||
    user?.role === "EXECUTIVE";

  const navItems = isEmployee ? employeeNav : customerNav;

  return (
    <aside className="w-64 bg-gray-900 text-white min-h-screen flex flex-col">
      <div className="p-6 border-b border-gray-800">
        <h1 className="text-xl font-bold text-amber-400">City Casting Corp</h1>
        <p className="text-xs text-gray-400 mt-1">Operating System</p>
      </div>

      <nav className="flex-1 py-4">
        {navItems.map((item) => {
          const isActive = pathname === item.href || pathname.startsWith(item.href + "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-6 py-3 text-sm transition-colors ${
                isActive
                  ? "bg-amber-600/20 text-amber-400 border-r-2 border-amber-400"
                  : "text-gray-300 hover:bg-gray-800 hover:text-white"
              }`}
            >
              {item.icon}
              {item.label}
            </Link>
          );
        })}
      </nav>

      <div className="p-4 border-t border-gray-800">
        <div className="flex items-center gap-3 mb-3">
          <div className="w-8 h-8 bg-amber-600 rounded-full flex items-center justify-center text-sm font-bold">
            {user?.firstName?.[0]}
            {user?.lastName?.[0]}
          </div>
          <div className="flex-1 min-w-0">
            <p className="text-sm font-medium truncate">
              {user?.firstName} {user?.lastName}
            </p>
            <p className="text-xs text-gray-400 truncate">
              {user?.role === "CUSTOMER"
                ? user?.companyName || "Customer"
                : user?.department || user?.role}
            </p>
          </div>
        </div>
        <button
          onClick={logout}
          className="w-full text-left text-sm text-gray-400 hover:text-white transition-colors px-2 py-1"
        >
          Sign Out
        </button>
      </div>
    </aside>
  );
}
